// 在 StartWebsite 构建界面之前注入中文翻译（OV.Engine 就绪后立即执行）
export function applyChineseLanguage() {
  const OV = window.OV
  if (!OV || !OV.Engine) return false
  if (typeof OV.Engine.SetLocalizedStrings === 'function') {
    OV.Engine.SetLocalizedStrings(ZH_TRANSLATIONS)
  }
  if (typeof OV.Engine.SetLanguageCode === 'function') {
    OV.Engine.SetLanguageCode('zh')
  }
  return true
}
